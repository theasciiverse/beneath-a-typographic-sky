#!/usr/bin/env python3
"""Translate ScummVM's engines/sky/skydefs.h, plus the enums in logic.h and
compact.h, into src/engine/defs.rs. Run from the project root."""
import re, sys

SRC = "reference/scummvm/engines/sky/"
out = []
vals = {}

def emit(name, expr, origin):
    e = re.sub(r"//.*", "", expr).strip()
    e = re.sub(r"/\*.*?\*/", "", e).strip()
    if not e:
        return
    py = re.sub(r"\b(0x[0-9a-fA-F]+|\d+)[uUlL]+\b", r"\1", e)
    try:
        v = eval(py, {}, dict(vals))
    except Exception as ex:
        print(f"skip {name} = {e!r} ({ex})", file=sys.stderr)
        return
    if not isinstance(v, int):
        print(f"skip {name} = {e!r}", file=sys.stderr)
        return
    if name in vals:
        if vals[name] != v:
            print(f"redefined {name}: {vals[name]} -> {v}", file=sys.stderr)
        return
    vals[name] = v
    out.append(f"pub const {name}: u32 = {v:#x};")

for line in open(SRC + "skydefs.h"):
    m = re.match(r"#define\s+(\w+)\s+(.*)", line)
    if m:
        emit(m.group(1), m.group(2), "skydefs")

def enum_block(path, start_pat):
    text = open(SRC + path).read()
    m = re.search(start_pat + r"\s*\{(.*?)\}", text, re.S)
    nxt = 0
    for item in m.group(1).split(","):
        item = re.sub(r"//.*", "", item).strip()
        if not item:
            continue
        if "=" in item:
            n, e = [x.strip() for x in item.split("=", 1)]
            nxt = eval(e, {}, dict(vals))
        else:
            n = item
        if n not in vals:
            vals[n] = nxt
            out.append(f"pub const {n}: u32 = {nxt:#x};")
        nxt += 1

enum_block("logic.h", r"enum scriptVariableOffsets")
enum_block("compact.h", r"enum CptIds")

hdr = ["//! Constants from ScummVM's engines/sky/skydefs.h, logic.h and compact.h.",
       "//! Generated by tools/gen_defs.py; do not edit by hand.",
       "#![allow(dead_code)]", ""]
open("src/engine/defs.rs", "w").write("\n".join(hdr + out) + "\n")
print(len(out), "constants", file=sys.stderr)
